"""Derive the public opcode table and inline assembly directly from RTL."""
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
text = (ROOT / "rtl/include/cvxif_instr_pkg.sv").read_text()
table = text.split("CoproInstr[NbInstr] = '{", 1)[1].split("parameter int unsigned NbCompInstr", 1)[0]
pattern = (r"instr:\s*32'b([01_]+).*?mask\s*:\s*32'b([01_]+).*?"
           r"writeback\s*:\s*1'b([01]).*?register_read\s*:\s*\{([^}]+)\}.*?"
           r"opcode\s*:\s*(\w+)")
entries = []
for value, mask, wb, reads, name in re.findall(pattern, table, re.S):
    entries.append({"opcode": name, "encoding": f"0x{int(value.replace('_',''),2):08x}",
                    "mask": f"0x{int(mask.replace('_',''),2):08x}",
                    "writeback": bool(int(wb)),
                    "read_old_rd_rs2_rs1": [int(x) for x in re.findall(r"1'b([01])", reads)]})
assert len(entries) == 38 and entries[0]["opcode"] == "NOP"
(ROOT / "software/instructions.json").write_text(json.dumps(entries, indent=2) + "\n")
header = ["// SPDX-License-Identifier: Apache-2.0 WITH SHL-2.0",
          "// Generated by scripts/generate_isa.py from the released RTL.",
          "#ifndef XMPK_ASM_H", "#define XMPK_ASM_H", "#include <stdint.h>",
          "// All raw entry points accept (rs1, rs2, old_rd); unused inputs are ignored.",
          "// Fixed a0/a1/a2 allocation supports assemblers without Xmpk mnemonics."]
for entry in entries:
    name = entry["opcode"].lower()
    ret = "uint64_t" if entry["writeback"] else "void"
    word = int(entry["encoding"], 16) | (10 << 15) | (11 << 20) | (12 << 7)
    header += [f"static inline {ret} xmpk_{name}(uint64_t rs1, uint64_t rs2, uint64_t old_rd) {{",
               '  register uint64_t a asm("a0") = rs1;',
               '  register uint64_t b asm("a1") = rs2;',
               '  register uint64_t c asm("a2") = old_rd;',
               f'  asm volatile(".balign 4\\n\\t.word 0x{word:08x}\\n\\tfence rw,rw" : "+r"(c) : "r"(a), "r"(b) : "memory");']
    if entry["writeback"]:
        header += ["  return c;"]
    header += ["}"]
header += ["#endif", ""]
(ROOT / "software/xmpk_asm.h").write_text("\n".join(header))
rows = ["# Instruction encodings", "",
        "Generated from `rtl/include/cvxif_instr_pkg.sv`. There are 37 Xmpk entries and one inherited NOP.",
        "All encodings use custom-3 (`0x7b`). Match `(instruction & mask) == (encoding & mask)`.",
        "Operands 1/2/3 are rs1/rs2/old(rd). Read bits below are listed in that order.",
        "Register fields remain variable, including GF16_MACC's intentionally unmasked high bits.",
        "", "| Opcode | Base encoding | Mask | Read rs1/rs2/old rd | Write rd |",
        "|---|---|---|---|---|"]
for e in entries:
    rows.append(f"| {e['opcode']} | {e['encoding']} | {e['mask']} | "
                f"{'/'.join(map(str,reversed(e['read_old_rd_rs2_rs1'])))} | {'yes' if e['writeback'] else 'no'} |")
rows += ["", "See [ISA usage](ISA.md) for configuration words, memory layouts and return values.", ""]
(ROOT / "docs/ENCODINGS.md").write_text("\n".join(rows))
# A compile-only probe calls every inline function, including the non-writing entries.
probe = ['// SPDX-License-Identifier: Apache-2.0 WITH SHL-2.0',
         '#include "xmpk_asm.h"', "uint64_t header_probe(uint64_t a, uint64_t b, uint64_t c) {"]
for e in entries:
    probe.append(f"  {'c = ' if e['writeback'] else ''}xmpk_{e['opcode'].lower()}(a, b, c);")
probe += ["  return c;", "}", ""]
(ROOT / "tests/header_probe.c").write_text("\n".join(probe))
enum = text.split("} opcode_t", 1)[0]
values = {name:int(bits,2) for name,bits in re.findall(r"(\w+)\s*=\s*\d+'b([01]+)",enum)}
cases = ["// SPDX-License-Identifier: Apache-2.0 WITH SHL-2.0",
         "// Generated from the released instruction package.",
         "struct DecodeCase { unsigned base, mask, op, reads, wb; };",
         "static constexpr DecodeCase decode_cases[] = {"]
for e in entries:
    reads = sum(bit << i for i,bit in enumerate(reversed(e["read_old_rd_rs2_rs1"])))
    cases += [f"  {{{e['encoding']}, {e['mask']}, {values[e['opcode']]}, {reads}, {int(e['writeback'])}}},"]
cases += ["};", ""]
(ROOT/"tests/decoder_cases.h").write_text("\n".join(cases))
