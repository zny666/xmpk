#!/usr/bin/env python3
"""Estimate on-chip energy for one KeyGen + Sign + Verify sequence."""
import argparse
import csv
import hashlib
import json
import re
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--update-protected-table", action="store_true",
                        help="Update TABLE VI energy rows only with explicit user authorization.")
    args = parser.parse_args()
    source = ROOT / "generated/e2e_measured.csv"
    power_source = ROOT / "generated/results.tex"
    macros = power_source.read_text()

    def power(name):
        return Decimal(re.search(
            rf"\\newcommand\{{\\{name}\}}\{{([^}}]+)\}}", macros
        ).group(1))

    baseline_power = power("CvaSixPowerTotal")
    xmpk_power = power("SystemPowerTotal")
    frequency = Decimal(40_000_000)
    rows = list(csv.DictReader(source.open()))
    order = ("UOV", "SNOVA", "MQOM", "MAYO", "QR-UOV")
    totals = []
    tex = ["% Generated by tools/estimate_algorithm_energy.py.",
           r"\newcommand{\AlgorithmEnergyRows}{%"]
    for family in order:
        for level in ("L1", "L5"):
            whole, = [r for r in rows if r["operation"] == "whole-run"
                      and r["level"] == level and r["scheme"].startswith(family)]
            stages = [r for r in rows if r["scheme"] == whole["scheme"]
                      and r["operation"] in ("keygen", "sign", "verify")]
            assert len(stages) == 3
            cycles = {}
            for field in ("baseline_cycles", "xmpk_cycles"):
                cycles[field] = sum(int(r[field]) for r in stages)
                assert cycles[field] == int(whole[field])
            baseline_energy = baseline_power * cycles["baseline_cycles"] / frequency
            xmpk_energy = xmpk_power * cycles["xmpk_cycles"] / frequency
            saving = (1 - xmpk_energy / baseline_energy) * 100
            totals.append({
                "scheme": whole["scheme"], "family": family, "level": level,
                **cycles, "frequency_hz": str(frequency),
                "baseline_power_w": str(baseline_power),
                "xmpk_power_w": str(xmpk_power),
                "baseline_energy_j": str(baseline_energy),
                "xmpk_energy_j": str(xmpk_energy),
                "saving_percent": str(saving),
                "cycle_status": whole["status"],
                "api_provenance": json.dumps(stages, sort_keys=True),
            })
            tex.append(f"{family} & {level} & {baseline_energy:.3f} & "
                       f"{xmpk_energy:.3f} & {saving:.2f} \\\\")
        if family != order[-1]:
            tex.append(r"\addlinespace[1pt]")
    tex.append("}")
    maximum = max(Decimal(r["saving_percent"]) for r in totals)
    tex.append(r"\newcommand{\AlgorithmMaxEnergySaving}{" + f"{maximum:.2f}" + "}")
    (ROOT / "generated/algorithm_energy_rows.tex").write_text("\n".join(tex) + "\n")
    with (ROOT / "generated/algorithm_energy.csv").open("w", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=totals[0].keys())
        writer.writeheader()
        writer.writerows(totals)
    metadata = {
        "formula": "E = P_total * (C_keygen + C_sign + C_verify) / 40000000",
        "scope": "Estimated on-chip total energy; external memory excluded.",
        "power_method": "Vivado post-route vectorless activity estimate.",
        "cycle_method": "Recorded API cycles, including validated factor-derived counts; no display clamping.",
        "sources_sha256": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in (source, power_source)},
        "results": totals,
    }
    (ROOT / "generated/algorithm_energy.json").write_text(
        json.dumps(metadata, indent=2) + "\n")
    combined_path = ROOT / "generated/e2e_energy_table_rows.tex"
    if args.update_protected_table:
        original = (ROOT / "generated/e2e_table_rows.tex").read_text().splitlines()
        combined = []
        index = 0
        for line in original:
            if line.startswith(r"\newcommand{\UpdatedEtoERows}"):
                line = line.replace("UpdatedEtoERows", "UpdatedEtoEEnergyRows")
            if "&" in line and line.endswith(r"\\"):
                result = totals[index]
                cells = [c.strip() for c in line[:-2].split("&")]
                assert cells[1] == result["level"]
                assert cells[0] in ("", result["family"])
                baseline = Decimal(result["baseline_energy_j"])
                optimized = Decimal(result["xmpk_energy_j"])
                for column in (2, 3, 4):
                    match = re.fullmatch(r"(\d+\.\d+)/(\d+\.\d+)( \[.*\])",
                                         cells[column])
                    assert match is not None
                    cells[column] = (
                        match[1] + r"/\textbf{" + match[2] + "}" + match[3]
                    )
                change = -Decimal(result["saving_percent"])
                sign = "-" if change < 0 else "+"
                cells.append(
                    f"{baseline:.3f}/" + r"\textbf{" + f"{optimized:.3f}"
                    + "} [" + rf"\({sign}{abs(change):.1f}\%\)" + "]"
                )
                line = " & ".join(cells) + r" \\"
                index += 1
            combined.append(line)
        assert index == 10
        combined_path.write_text("\n".join(combined) + "\n")
    elif not combined_path.exists():
        raise RuntimeError("TABLE VI energy rows need explicit authorized generation.")
    print(f"Validated {len(totals)} API sums; maximum estimated energy saving {maximum:.2f}%")


if __name__ == "__main__":
    main()
